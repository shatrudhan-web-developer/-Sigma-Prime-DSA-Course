//Print the largest of 2 numbers :

/*
Number 1 = 1
Number 2 = 3
*/

public class A3_Que_01 {
    public static void main(String args[]) {

        int Number1 = 1;
        int Number2 = 3;

        // Check largest number

        if(Number1 >= Number2) {
            System.out.println("Number1 is largest of 2 : " + Number1);
        }

        else {
            System.out.println("Number2  is largest of 2 : " + Number2);
        }
    }
}