/*
Arithmatic operators ka use mathematical calculation ke liye hota hai.

Types :
1. Binary Operators : (+, -, *, /, %)
2. Unary Operators : (++, --)
*/

public class B2 {
    public static void main(String args[]) {

        int a = 50;
        int b = 10;

        System.out.println("Addition = " + (a + b));
        System.out.println("Subtraction = " + (a - b));
        System.out.println("Multiplication = " + (a * b));
        System.out.println("Division = " + (a / b));
        System.out.println("Modulus/Remender = " + (a % b));
    }
}