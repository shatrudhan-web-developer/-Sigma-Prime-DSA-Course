//Variables in Java :

/*
A variables is a named memory location used to store data.

Syntax :
    dataType variableName = value;

Example :
    int age = 19;
    String name = "Shatrudhan";
*/

public class E1 {
    public static void main(String args[]) {
        int age = 19;
        String name = "Shtrudhan";

        System.out.println(age);
        System.out.println(name);
    }
}