// Type casting :

/*
Type Casting is the manual conversion of a larger data type into a smaller
data type.

Rule :
    int marks = (int)(99.99f);
 */

public class O1 {
    public static void main(String args[]) {

        float a = 25.56f;
        int b = (int)a;

        System.out.println(b);
    }
}