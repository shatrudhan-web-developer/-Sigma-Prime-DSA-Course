/*
Java provides three methods of display output.

1. print() :
    Print Text on the same line'

    Example :
        System.out.print("Hello");
        System.out.print("Java");

2. println() :
    Print text and moves to the next line.

    Example :
        System.out.println("Hello");
        System.out.println("Mayra");

3. "\n" :
    Same as println().

        Example :
        System.out.print("Hello \n Mayra \n Daiya");

*/

