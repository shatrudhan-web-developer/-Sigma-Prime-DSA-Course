// How does java code run? :

/*
Step 1: Write Source Code :
                ↓
        Create a file
                ↓
            Hell.java

Step 2. Compilation :
            ↓
        javac Hello.java

The java compile converts the source code into Bytecode.
                        ↓
                    Hello.class

Step 3. JVM Execution :
                ↓
        Run the program
                ↓
        java Hello.java

The JVM (Java Virtual Machine) converts the bytecode into machine code and
executes it.
 */